#!/usr/bin/env bash
set -euo pipefail

# Host entrypoint: every build runs inside AOWIS's pinned Android Docker image.
# The host does NOT need Qt, Android SDK/NDK, Java or CMake.
project_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
# shellcheck source=tools/qt-android/toolchain_versions.sh
source "$project_dir/tools/qt-android/toolchain_versions.sh"

usage() {
    cat <<'HELP'
Usage: ./compile_android.sh [--build-only] [--run] [--baseline] [--help]

  (default)      Build a debug Android ARM64 APK in Docker. Install and launch
                 if exactly one authorized host ADB device is attached.
  --build-only   Build the APK without attempting installation.
  --run          Require an authorized device; build, install and launch.
  --baseline     Build QML-only (no bgfx), in build-android-baseline.

First invocation automatically prepares the Docker image; no Qt Online
Installer, Android Studio, or host SDK/JDK is necessary. The *host* needs Docker,
plus adb (Arch: android-tools) if deploying to a connected device.
Run ./prepare_android_docker.sh to provision/rebuild the toolchain explicitly.
Run ./tools/init_bgfx.sh once for the bgfx source submodule.

Optional overrides:
  AOWIS_ANDROID_IMAGE             Docker image name (default pinned by repo)
  AOWIS_ANDROID_JOBS              Build parallelism (default 8)
  AOWIS_DOCKER_RUN_NETWORK        Docker run network (default host)
  AOWIS_DOCKER_BUILD_NETWORK      Docker build network (default host)
  ANDROID_SERIAL                  Host ADB device serial when multiple exist
HELP
}

die() { printf 'AOWIS Mobile Android: %s\n' "$*" >&2; exit 1; }

install_mode=auto
bgfx=ON
for argument in "$@"; do
    case "$argument" in
        --build-only)
            [[ "$install_mode" != run ]] || die 'Do not combine --run and --build-only.'
            install_mode=build-only ;;
        --run)
            [[ "$install_mode" != build-only ]] || die 'Do not combine --build-only and --run.'
            install_mode=run ;;
        --baseline) bgfx=OFF ;;
        --help|-h) usage; exit 0 ;;
        *) usage >&2; exit 2 ;;
    esac
done

command -v docker >/dev/null 2>&1 || die 'Docker is missing (Arch: sudo pacman -S docker).'
if [[ "$bgfx" == ON && ! -f "$project_dir/external/bgfx.cmake/bgfx/include/bgfx/bgfx.h" ]]; then
    die 'bgfx is not initialized. Run ./tools/init_bgfx.sh first.'
fi
jobs="${AOWIS_ANDROID_JOBS:-8}"
[[ "$jobs" =~ ^[1-9][0-9]*$ ]] || die 'AOWIS_ANDROID_JOBS must be a positive integer.'

build_name=build-android-bgfx
[[ "$bgfx" == ON ]] || build_name=build-android-baseline

# Provisioning is separate from compiling and cached by the Docker image tag.
if ! docker image inspect "$AOWIS_ANDROID_IMAGE" >/dev/null 2>&1; then
    echo '=== Android Docker toolchain missing; preparing image ==='
    "$project_dir/prepare_android_docker.sh"
fi

# Share a persistent, host-owned Gradle cache so repeated APK builds do not
# re-download the Gradle distribution and Android plugin every time.
cache_root="${XDG_CACHE_HOME:-$HOME/.cache}/aowis-mobile/gradle"
mkdir -p "$cache_root"
echo "=== Compiling Android APK with Docker: $AOWIS_ANDROID_IMAGE ==="
docker run --rm --network="${AOWIS_DOCKER_RUN_NETWORK:-host}" \
    --user "$(id -u):$(id -g)" \
    -v "$project_dir:/project" -w /project \
    -v "$cache_root:/gradle-cache" \
    -e HOME=/tmp \
    -e GRADLE_USER_HOME=/gradle-cache \
    -e "AOWIS_QT_ANDROID_VERSION=$AOWIS_QT_ANDROID_VERSION" \
    -e "AOWIS_ANDROID_NDK_VERSION=$AOWIS_ANDROID_NDK_VERSION" \
    -e "AOWIS_ANDROID_BGFX=$bgfx" \
    -e "AOWIS_ANDROID_BUILD_NAME=$build_name" \
    -e "AOWIS_ANDROID_JOBS=$jobs" \
    "$AOWIS_ANDROID_IMAGE" \
    /bin/bash /project/tools/qt-android/build_android_inside_container.sh \
    || die 'Docker APK build failed; no APK was deployed.'

# The normal debug APK location generated by Qt's Gradle deployment system.
search_dir="$project_dir/$build_name/android-build/build/outputs/apk/debug"
[[ -d "$search_dir" ]] || die "No debug APK directory after successful build: $search_dir"
mapfile -t apks < <(find "$search_dir" -maxdepth 1 -type f -name '*.apk' -print | sort)
(( ${#apks[@]} == 1 )) || die "Expected exactly one debug APK; found ${#apks[@]} in $search_dir"
apk="${apks[0]}"
[[ -s "$apk" ]] || die "APK missing or empty: $apk"
echo "=== APK ready: $apk ==="

[[ "$install_mode" != build-only ]] || exit 0
if ! command -v adb >/dev/null 2>&1; then
    [[ "$install_mode" != run ]] || die 'adb is missing (Arch: sudo pacman -S android-tools).'
    echo 'adb unavailable; skipping device deployment.'
    exit 0
fi

if [[ -n "${ANDROID_SERIAL:-}" ]]; then
    serial="$ANDROID_SERIAL"
    [[ "$(adb -s "$serial" get-state 2>/dev/null || true)" == device ]] || die "ADB device unavailable: $serial"
else
    mapfile -t devices < <(adb devices | awk 'NR > 1 && $2 == "device" { print $1 }')
    if (( ${#devices[@]} != 1 )); then
        [[ "$install_mode" != run ]] || die "Expected one authorized Android device; found ${#devices[@]}."
        echo "Authorized Android devices: ${#devices[@]}; skipping deployment."
        exit 0
    fi
    serial="${devices[0]}"
fi

echo "=== Installing and launching on $serial ==="
adb -s "$serial" install -r "$apk"
adb -s "$serial" shell monkey -p org.aowis.mobile.renderlab -c android.intent.category.LAUNCHER 1
echo '=== AOWIS Mobile launched ==='
